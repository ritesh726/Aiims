-- Run once in Supabase Dashboard > SQL Editor for the project configured in the CBT HTML files.
-- Uses Supabase Auth user IDs; students can only read/insert their own attempts.

create table if not exists public.test_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  test_id text not null,
  test_name text not null,
  total_questions integer not null,
  attempted integer not null default 0,
  correct integer,
  incorrect integer,
  unattempted integer not null default 0,
  score numeric,
  accuracy numeric,
  attempt_number integer not null,
  question_details jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  constraint test_attempts_attempt_number_positive check (attempt_number > 0),
  constraint test_attempts_user_test_attempt_unique unique (user_id, test_id, attempt_number)
);

alter table public.test_attempts
  add column if not exists user_id uuid references auth.users(id) on delete cascade,
  add column if not exists test_id text,
  add column if not exists test_name text,
  add column if not exists total_questions integer,
  add column if not exists attempted integer not null default 0,
  add column if not exists correct integer,
  add column if not exists incorrect integer,
  add column if not exists unattempted integer not null default 0,
  add column if not exists score numeric,
  add column if not exists accuracy numeric,
  add column if not exists attempt_number integer,
  add column if not exists question_details jsonb not null default '[]'::jsonb,
  add column if not exists created_at timestamptz not null default now();

alter table public.test_attempts enable row level security;

drop policy if exists "Students can read their own attempts" on public.test_attempts;
create policy "Students can read their own attempts"
on public.test_attempts for select
to authenticated
using (auth.uid() = user_id);

drop policy if exists "Students can insert their own attempts" on public.test_attempts;
create policy "Students can insert their own attempts"
on public.test_attempts for insert
to authenticated
with check (auth.uid() = user_id);

grant select, insert on public.test_attempts to authenticated;

create index if not exists test_attempts_user_test_created_idx
on public.test_attempts (user_id, test_id, created_at desc);

-- Enforce sequential attempt identity even if the table existed before this setup.
create unique index if not exists test_attempts_user_test_attempt_unique_idx
on public.test_attempts (user_id, test_id, attempt_number);
